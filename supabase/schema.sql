-- Schema do Sorteios do Soares (versão nova, no padrão do site Barr4k).
-- Rodar inteiro no SQL Editor do Supabase. ATENÇÃO: apaga as tabelas antigas
-- (sorteios, tickets, ganhadores) e recria do zero.
--
-- Regra central: o navegador nunca fala direto com as tabelas. Tudo passa pelas
-- rotas /api do site, que conferem quem está chamando e usam a service role.
-- Por isso o RLS fica ligado em todas as tabelas e não existe nenhuma policy.

drop view  if exists public.sorteios_resumo;
drop table if exists public.ganhadores cascade;
drop table if exists public.fair_draws cascade;
drop table if exists public.chat_participantes cascade;
drop table if exists public.tickets cascade;
drop table if exists public.sorteios cascade;

create extension if not exists pgcrypto;

-- ========== SORTEIOS ==========
-- tipo 'ticket': entra quem manda print de depósito com o código SOARES (chances = coins)
-- tipo 'chat':   entra quem digita o comando no chat da Twitch (chances pelo tier do sub)
create table public.sorteios (
  id          uuid primary key default gen_random_uuid(),
  tipo        text not null default 'ticket' check (tipo in ('ticket', 'chat')),
  titulo      text not null,
  descricao   text,
  imagem_url  text,                                   -- URL pública no bucket "premios"
  valor       numeric(12, 2),                         -- valor do prêmio em reais
  status      text not null default 'aberto' check (status in ('aberto', 'encerrado')),
  fecha_em    timestamptz,                            -- quando fecham as inscrições (opcional)
  -- só para tipo 'chat'
  canal       text,                                   -- canal da Twitch (login)
  comando     text not null default '!sorteio',
  captando    boolean not null default false,         -- chat aberto para entrar
  chance_t1   integer not null default 2 check (chance_t1 >= 1),
  chance_t2   integer not null default 3 check (chance_t2 >= 1),
  chance_t3   integer not null default 5 check (chance_t3 >= 1),
  criado_em   timestamptz not null default now()
);
create index sorteios_status_idx on public.sorteios (status, criado_em desc);

-- ========== TICKETS (sorteios por depósito) ==========
create table public.tickets (
  id          bigint generated by default as identity primary key,
  sorteio_id  uuid not null references public.sorteios(id) on delete cascade,
  email       text not null,                          -- conta Google de quem mandou
  nome        text,
  avatar_url  text,
  casa        text not null check (casa in ('csgobig', 'dastskin')),
  casa_id     text not null,                          -- ID da pessoa na casa
  coins       integer not null check (coins > 0),
  instagram   text not null,
  print_path  text not null,                          -- caminho no bucket privado "prints"
  status      text not null default 'pendente' check (status in ('pendente', 'aprovado', 'recusado')),
  criado_em   timestamptz not null default now()
);
create index tickets_sorteio_idx on public.tickets (sorteio_id, status);
create index tickets_email_idx   on public.tickets (email, criado_em desc);

-- ========== PARTICIPANTES DO CHAT (sorteios pela Twitch) ==========
create table public.chat_participantes (
  id           bigint generated by default as identity primary key,
  sorteio_id   uuid not null references public.sorteios(id) on delete cascade,
  twitch_login text not null,
  avatar_url   text,
  sub_tier     smallint not null default 0 check (sub_tier between 0 and 3),
  removido     boolean not null default false,        -- tirado da lista pelo admin
  criado_em    timestamptz not null default now(),
  unique (sorteio_id, twitch_login)
);

-- ========== PROVABLY FAIR ==========
-- Cada giro fica registrado: a lista é congelada (com hash SHA-256) antes de existir
-- o número público (rodada futura do drand). Qualquer um refaz a conta em /provably-fair.
create table public.fair_draws (
  id               uuid primary key default gen_random_uuid(),
  kind             text not null check (kind in ('ticket', 'chat')),
  target_id        uuid not null references public.sorteios(id) on delete cascade,
  title            text not null,
  entries          jsonb not null,                    -- [{ "label": "@fulano", "weight": 5000 }, ...]
  total_weight     bigint not null check (total_weight > 0),
  entries_hash     text not null,
  drand_round      bigint not null,
  drand_randomness text,
  drand_signature  text,
  ticket           text,
  winner_label     text,
  winner_ref       text,                              -- e-mail (ticket) ou login (chat); nunca sai na página pública
  status           text not null default 'waiting' check (status in ('waiting', 'drawn', 'confirmed', 'skipped')),
  created_at       timestamptz not null default now(),
  drawn_at         timestamptz
);
create index fair_draws_target_idx on public.fair_draws (target_id, created_at);
create index fair_draws_recent_idx on public.fair_draws (created_at desc);

-- ========== GANHADORES ==========
create table public.ganhadores (
  id           bigint generated by default as identity primary key,
  sorteio_id   uuid not null references public.sorteios(id) on delete cascade,
  rodada       integer not null default 1,
  nome         text not null,                         -- @instagram (ticket) ou login da Twitch (chat)
  email        text,                                  -- dono dos tickets (só no ticket)
  casa         text,
  casa_id      text,
  coins        integer,                               -- soma das coins aprovadas da pessoa
  fair_draw_id uuid references public.fair_draws(id) on delete set null,
  criado_em    timestamptz not null default now()
);
create index ganhadores_sorteio_idx on public.ganhadores (sorteio_id, rodada);
create index ganhadores_recentes_idx on public.ganhadores (criado_em desc);

-- ========== RESUMO (contagens leves pra home) ==========
create view public.sorteios_resumo with (security_invoker = true) as
select
  s.id,
  count(t.id) filter (where t.status = 'aprovado')                        as tickets,
  coalesce(sum(t.coins) filter (where t.status = 'aprovado'), 0)::bigint  as coins,
  count(t.id) filter (where t.status = 'pendente')                        as pendentes,
  (select count(*) from public.chat_participantes c where c.sorteio_id = s.id and not c.removido) as chat
from public.sorteios s
left join public.tickets t on t.sorteio_id = s.id
group by s.id;

-- ========== ACESSO ==========
alter table public.sorteios           enable row level security;
alter table public.tickets            enable row level security;
alter table public.chat_participantes enable row level security;
alter table public.fair_draws         enable row level security;
alter table public.ganhadores         enable row level security;

revoke all on public.sorteios, public.tickets, public.chat_participantes, public.fair_draws, public.ganhadores, public.sorteios_resumo from anon, authenticated;
grant all on public.sorteios, public.tickets, public.chat_participantes, public.fair_draws, public.ganhadores, public.sorteios_resumo to service_role;
grant usage, select on all sequences in schema public to service_role;

-- ========== STORAGE ==========
-- premios: imagens dos prêmios, públicas (a home mostra direto)
-- prints:  comprovantes de depósito, privados (o painel abre com link temporário)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('premios', 'premios', true,  10485760, array['image/png', 'image/jpeg', 'image/webp', 'image/gif', 'image/avif']),
  ('prints',  'prints',  false,  8388608, array['image/png', 'image/jpeg', 'image/webp'])
on conflict (id) do update
  set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

-- Sem policy de escrita pra ninguém de fora: uploads só com link assinado gerado pelo servidor
drop policy if exists "prints leitura publica" on storage.objects;
drop policy if exists "prints upload anon"     on storage.objects;
