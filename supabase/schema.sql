-- Schema do Sorteios-Cs2 (reconstruído a partir do código em src/)
-- Rodar inteiro no SQL Editor de um projeto Supabase novo.

-- ========== TABELAS ==========
create table if not exists public.sorteios (
  id             text primary key,             -- Date.now().toString() no admin
  nome           text not null,
  descricao      text,
  destaque_texto text,
  destaque_cor   text,
  img            text,                          -- data URL (base64) ou link
  valor          text,
  status         text not null default 'Ativo'  -- 'Ativo' | 'Finalizado'
);

create table if not exists public.tickets (
  id          bigint generated by default as identity primary key,
  sorteio_id  text references public.sorteios(id) on delete cascade,
  email       text,
  user_image  text,
  csgobig_id  text,
  coins       numeric default 0,
  instagram   text,
  print       text,                             -- URL pública do bucket "prints"
  status      text not null default 'Pendente', -- 'Pendente' | 'Aprovado' | 'Recusado'
  data        text                              -- toLocaleString() do navegador
);

create table if not exists public.ganhadores (
  id          bigint generated by default as identity primary key,
  sorteio_id  text references public.sorteios(id) on delete cascade,
  ticket_id   bigint references public.tickets(id) on delete cascade,
  round       integer,
  data_ganhou text
);

create index if not exists tickets_sorteio_id_idx on public.tickets (sorteio_id);
create index if not exists tickets_email_idx      on public.tickets (email);
create index if not exists ganhadores_sorteio_idx on public.ganhadores (sorteio_id);

-- Projetos novos do Supabase não dão acesso automático às tabelas pro anon
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.sorteios, public.tickets, public.ganhadores to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ========== RLS ==========
-- O site usa NextAuth (não Supabase Auth) e fala com o banco só pela anon key,
-- então as políticas liberam o papel anon, igual ao projeto antigo.
alter table public.sorteios   enable row level security;
alter table public.tickets    enable row level security;
alter table public.ganhadores enable row level security;

drop policy if exists "acesso publico" on public.sorteios;
drop policy if exists "acesso publico" on public.tickets;
drop policy if exists "acesso publico" on public.ganhadores;
create policy "acesso publico" on public.sorteios   for all to anon, authenticated using (true) with check (true);
create policy "acesso publico" on public.tickets    for all to anon, authenticated using (true) with check (true);
create policy "acesso publico" on public.ganhadores for all to anon, authenticated using (true) with check (true);

-- ========== STORAGE (prints dos tickets) ==========
insert into storage.buckets (id, name, public)
values ('prints', 'prints', true)
on conflict (id) do update set public = true;

drop policy if exists "prints leitura publica" on storage.objects;
drop policy if exists "prints upload anon"     on storage.objects;
create policy "prints leitura publica" on storage.objects for select to anon, authenticated using (bucket_id = 'prints');
create policy "prints upload anon"     on storage.objects for insert to anon, authenticated with check (bucket_id = 'prints');
